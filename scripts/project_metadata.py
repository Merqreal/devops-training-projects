"""Load project definitions, validate contracts, and render deterministic catalog/navigation."""
import argparse
import json
from pathlib import Path
import sys
import tomllib

from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parents[1]


def load_projects(root=ROOT):
    schema = json.loads((root / 'platform/schemas/project.schema.json').read_text())
    Draft202012Validator.check_schema(schema)
    validator = Draft202012Validator(schema)
    projects = []
    errors = []
    for path in sorted((root / 'projects').glob('*/project.json')):
        try:
            data = json.loads(path.read_text())
        except ValueError as exc:
            errors.append(f'{path}: {exc}')
            continue
        issues = list(validator.iter_errors(data))
        if issues:
            errors.extend(f'{path}: {".".join(map(str, e.absolute_path))}: {e.message}' for e in issues)
            continue
        projects.append(data)
        if path.parent.name != data['id']:
            errors.append(f'{path}: definition folder must match permanent ID')
    if not projects:
        errors.append('No valid project definitions')
    ids = [p['id'] for p in projects]
    content_paths = [p['content_path'] for p in projects]
    if len(set(ids)) != len(ids):
        errors.append('Duplicate project ID')
    if len(set(content_paths)) != len(content_paths):
        errors.append('Duplicate canonical content path')
    for project in projects:
        ident = project['id']
        if project['primary_domain'] not in project['domains']:
            errors.append(f'{ident}: primary_domain missing from domains')
        if project['content_path'].split('/')[1] != project['primary_domain']:
            errors.append(f'{ident}: content path must use primary domain')
        if project['estimated_effort']['min'] > project['estimated_effort']['max']:
            errors.append(f'{ident}: minimum effort exceeds maximum')
        pages = project['pages']
        if pages[0]['file'] != 'index.md':
            errors.append(f'{ident}: first page must be index.md')
        for key in ('title', 'file'):
            if len({p[key] for p in pages}) != len(pages):
                errors.append(f'{ident}: duplicate page {key}')
        for page in pages:
            target = root / 'docs' / project['content_path'] / page['file']
            if not target.is_file():
                errors.append(f'{ident}: missing content page {target}')
        reviewer = root / 'reviewers' / f'{ident}.md'
        if not reviewer.is_file():
            errors.append(f'{ident}: missing separate reviewer notes')
        references = project['prerequisites']['projects'][:]
        replacement = project.get('deprecation', {}).get('replacement_id')
        if replacement:
            references.append(replacement)
        for reference in references:
            if reference not in ids or reference == ident:
                errors.append(f'{ident}: invalid project reference {reference}')
    if errors:
        raise ValueError('\n'.join(errors))
    return sorted(projects, key=lambda p: int(p['id'].split('-')[1]))


def domain_title(slug):
    return slug.replace('-', ' ').title()


def project_navigation(projects):
    groups = [{'Project catalog': 'projects/index.md'}]
    for domain in sorted({p['primary_domain'] for p in projects}):
        entries = []
        for project in projects:
            if project['primary_domain'] == domain:
                label = f"{project['id']} · {project['title']}"
                entries.append({label: [{page['title']: f"{project['content_path']}/{page['file']}"}
                                        for page in project['pages']]})
        groups.append({domain_title(domain): entries})
    return groups


def catalog(projects):
    lines = ['# Project catalog', '', '<!-- Generated by scripts/project_metadata.py --write; edit definitions instead. -->', '',
             'Projects are grouped by primary technical domain. Difficulty is a filterable metadata field, never a directory.', '']
    for domain in sorted({p['primary_domain'] for p in projects}):
        lines += [f'## {domain_title(domain)}', '',
                  '| ID | Project | Difficulty | Effort | Lifecycle | Technologies |',
                  '| --- | --- | --- | --- | --- | --- |']
        selected = [p for p in projects if p['primary_domain'] == domain]
        for p in selected:
            effort = p['estimated_effort']
            link = p['content_path'].removeprefix('projects/') + '/index.md'
            lines.append(f"| {p['id']} | [{p['title']}]({link}) | {p['difficulty']} | {effort['min']}–{effort['max']} hours | {p['status']} | {', '.join(p['technologies'])} |")
        for p in selected:
            lines += ['', f"### {p['id']} learning objectives", '']
            lines += [f'- {objective}' for objective in p['learning_objectives']]
            lines += ['', f"**Tags:** {', '.join(p['tags'])}. **Domains:** {', '.join(p['domains'])}."]
            if p.get('deprecation'):
                lines += ['', f"**{p['status'].title()}:** {p['deprecation']['reason']}"]
                if p['deprecation'].get('replacement_id'):
                    replacement = next(x for x in projects if x['id'] == p['deprecation']['replacement_id'])
                    link = replacement['content_path'].removeprefix('projects/') + '/index.md'
                    lines += [f"Replacement: [{replacement['id']}]({link})."]
    return '\n'.join(lines) + '\n'


def validate_views(projects, root=ROOT):
    config = tomllib.loads((root / 'zensical.toml').read_text())['project']
    sections = [section['Projects'] for section in config['nav'] if 'Projects' in section]
    errors = []
    if sections != [project_navigation(projects)]:
        errors.append('Projects navigation differs from metadata; run project_metadata.py --navigation to inspect expected tree')
    path = root / 'docs/projects/index.md'
    if not path.is_file() or path.read_text() != catalog(projects):
        errors.append('Catalog is stale; run python scripts/project_metadata.py --write')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate the project catalog')
    parser.add_argument('--navigation', action='store_true', help='Print expected Projects navigation as JSON')
    args = parser.parse_args()
    try:
        projects = load_projects()
        if args.write:
            (ROOT / 'docs/projects/index.md').write_text(catalog(projects))
        if args.navigation:
            print(json.dumps(project_navigation(projects), indent=2))
        errors = validate_views(projects)
        if errors:
            raise ValueError('\n'.join(errors))
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    print(f'Validated {len(projects)} definitions against schema v1, catalog and domain navigation.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
